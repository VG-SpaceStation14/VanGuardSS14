using System.Collections.Generic;
using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI.Roles;

[GenerateTypedNameReferences]
public sealed partial class TraitPreferenceSelector : Control
{
    public int Cost;

    public bool Preference
    {
        get => Checkbox.Pressed;
        set => Checkbox.Pressed = value;
    }

    public event Action<bool>? PreferenceChanged;

    private readonly string _description = string.Empty;

    public TraitPreferenceSelector(TraitPrototype trait)
    {
        RobustXamlLoader.Load(this);

        // VG-Tweak Start: positive quirks cost points, negative ones refund them. Make the sign explicit.
        var text = trait.Cost switch
        {
            > 0 => $"[{trait.Cost}] ",
            < 0 => $"[+{-trait.Cost}] ",
            _ => string.Empty,
        };
        // VG-Tweak End
        text += Loc.GetString(trait.Name);

        Cost = trait.Cost;
        Checkbox.Text = text;
        Checkbox.OnToggled += OnCheckBoxToggled;

        // VG-Tweak Start: keep the description as the base tooltip and append the point cost information.
        var tooltipParts = new List<string>();

        if (trait.Description is { } desc)
            tooltipParts.Add(Loc.GetString(desc));

        if (trait.Cost != 0)
        {
            tooltipParts.Add(trait.Cost > 0
                ? Loc.GetString("vg-trait-cost-hint", ("cost", trait.Cost))
                : Loc.GetString("vg-trait-refund-hint", ("cost", -trait.Cost)));
        }

        _description = string.Join("\n", tooltipParts);
        ToolTip = _description;
        // VG-Tweak End
    }

    /// <summary>
    ///     VG-Tweak: disables the selector and explains why the trait can not be selected right now.
    ///     The reason is appended to the description so it is always visible on hover.
    /// </summary>
    public void SetAvailability(bool available, string? reason = null)
    {
        Checkbox.Disabled = !available;

        if (available || string.IsNullOrEmpty(reason))
        {
            ToolTip = _description;
            return;
        }

        ToolTip = string.IsNullOrEmpty(_description) ? reason : $"{_description}\n\n{reason}";
    }

    private void OnCheckBoxToggled(BaseButton.ButtonToggledEventArgs args)
    {
        PreferenceChanged?.Invoke(Preference);
    }
}
