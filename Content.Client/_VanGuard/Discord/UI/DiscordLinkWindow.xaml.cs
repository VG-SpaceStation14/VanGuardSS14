using System;
using Content.Client._VanGuard.Discord;
using Content.Client.UserInterface.Controls;
using Content.Shared.CCVar;
using Content.Shared._VanGuard.Sponsors;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Timing;
using Robust.Shared.Utility;
using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client._VanGuard.Discord.UI;

[GenerateTypedNameReferences]
public sealed partial class DiscordLinkWindow : FancyWindow
{
    private enum State { Loading, Unlinked, Waiting, Code, Linked }

    [Dependency] private ClientDiscordAuthManager _auth = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IUriOpener _uriOpener = default!;
    [Dependency] private IClipboardManager _clipboard = default!;

    private State _state = State.Loading;
    private readonly System.Threading.CancellationTokenSource _timerCancel = new();

    public DiscordLinkWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        GetCodeButton.OnPressed += _ =>
        {
            _auth.RequestCode();
            SetState(State.Waiting);
        };

        CopyButton.OnPressed += _ =>
        {
            if (!string.IsNullOrEmpty(CodeLabel.Text))
                _clipboard.SetText(CodeLabel.Text);
        };

        OpenDiscordButton.OnPressed += _ => OpenDiscord();
        OpenDiscordLinkedButton.OnPressed += _ => OpenDiscord();

        _auth.OnCodeReceived += OnCodeReceived;
        _auth.OnStateReceived += OnStateReceived;

        SetState(State.Loading);
        _auth.RequestState();
    }

    protected override void Opened()
    {
        base.Opened();
        Timer.SpawnRepeating(TimeSpan.FromSeconds(2), () =>
        {
            if (_state != State.Linked)
                _auth.RequestState();
        }, _timerCancel.Token);
    }

    public override void Close()
    {
        _timerCancel.Cancel();
        base.Close();
    }

    private void SetState(State state)
    {
        _state = state;
        LoadingState.Visible = state == State.Loading;
        UnlinkedState.Visible = state == State.Unlinked;
        WaitingState.Visible = state == State.Waiting;
        CodeState.Visible = state == State.Code;
        LinkedState.Visible = state == State.Linked;
    }

    private void OpenDiscord()
    {
        var url = _cfg.GetCVar(CCVars.InfoLinksDiscord);
        if (!string.IsNullOrEmpty(url)) _uriOpener.OpenUri(url);
    }

    private void OnCodeReceived(string code)
    {
        CodeLabel.Text = code;
        CodeLabel.ModulateSelfOverride = Color.FromHex("#4CAF50");
        SetState(State.Code);
    }

    private void OnStateReceived(bool isLinked, int tier, string tierName, string timeLeft)
    {
        if (isLinked)
        {
            if (tier > 0)
            {
                var hex = SponsorVisuals.GetHex(tier);
                var markup = $"[color={hex}]{Loc.GetString("discord-link-tier-info", ("tierName", tierName))}[/color]";
                TierLabel.SetMessage(FormattedMessage.FromMarkup(markup));
                TimeLeftLabel.Text = timeLeft;
            }
            else
            {
                TierLabel.SetMessage(FormattedMessage.FromMarkup(Loc.GetString("discord-link-no-subscription")));
                TimeLeftLabel.Text = string.Empty;
            }

            SetState(State.Linked);
            return;
        }

        if (_state == State.Loading)
            SetState(State.Unlinked);
    }
}
