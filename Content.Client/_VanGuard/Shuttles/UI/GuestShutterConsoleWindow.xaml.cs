using Content.Client.UserInterface.Controls;
using Content.Shared._VanGuard.Shuttles;
using Content.Shared.Access.Systems;
using Content.Shared.Doors.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Timing;

namespace Content.Client._VanGuard.Shuttles.UI;

[GenerateTypedNameReferences]
public sealed partial class GuestShutterConsoleWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPlayerManager _player = default!;

    public event Action<NetEntity>? OnToggle;

    private readonly EntityUid _owner;
    private readonly AccessReaderSystem _access;
    private GuestShutterEntry? _selected;

    public GuestShutterConsoleWindow(EntityUid owner)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _owner = owner;
        _access = _entMan.System<AccessReaderSystem>();

        Shutters.OnItemSelected += args =>
        {
            if (args.ItemIndex >= 0 && args.ItemIndex < _entries.Count)
                _selected = _entries[args.ItemIndex];
        };
        Shutters.OnItemDeselected += _ => _selected = null;
        ToggleButton.OnPressed += _ =>
        {
            if (_selected is { } entry)
                OnToggle?.Invoke(entry.Door);
        };
    }

    private readonly List<GuestShutterEntry> _entries = new();

    public void UpdateState(GuestShutterConsoleState state)
    {
        _entries.Clear();
        _entries.AddRange(state.Shutters);
        Shutters.Clear();

        foreach (var entry in _entries)
        {
            Shutters.AddItem($"{entry.Name}: {Loc.GetString($"guest-shutter-state-{entry.State}")}");
        }

        Status.Text = state.Error ?? string.Empty;
        UpdateButton();
    }

    private void UpdateButton()
    {
        ToggleButton.Disabled = _selected == null ||
                                !HasAccess();
    }

    private bool HasAccess()
    {
        return _player.LocalSession?.AttachedEntity is { } player &&
               _access.IsAllowed(player, _owner);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateButton();
    }
}
