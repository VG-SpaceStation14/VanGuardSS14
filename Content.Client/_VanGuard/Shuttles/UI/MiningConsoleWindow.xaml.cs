using Content.Client.UserInterface.Controls;
using Content.Shared._VanGuard.Shuttles;
using Content.Shared.Access.Systems;
using Content.Shared.Shuttles.Systems;
using Content.Shared.Timing;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Timing;
using Robust.Shared.Localization;

namespace Content.Client._VanGuard.Shuttles.UI;

[GenerateTypedNameReferences]
public sealed partial class MiningConsoleWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IPlayerManager _player = default!;

    public event Action<int>? OnTravel;

    private readonly AccessReaderSystem _access;
    private readonly EntityUid _owner;
    private int? _selected;
    private FTLState _state;
    private StartEndTime _ftlTime;
    private bool _hasShuttle;

    public MiningConsoleWindow(EntityUid owner)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _owner = owner;
        _access = _entMan.System<AccessReaderSystem>();

        Destinations.OnItemSelected += args => _selected = args.ItemIndex;
        Destinations.OnItemDeselected += _ => _selected = null;
        FTLButton.OnPressed += _ =>
        {
            if (_selected is { } index)
                OnTravel?.Invoke(index);
        };
    }

    public void UpdateState(MiningShuttleConsoleState state)
    {
        _state = state.FTLState;
        _ftlTime = state.FTLTime;
        _hasShuttle = state.HasShuttle;
        Title = state.Title;

        MapFTLState.Text = state.Error ??
                            Loc.GetString($"shuttle-console-ftl-state-{_state}");

        if (state.Destinations.Count != Destinations.Count)
        {
            Destinations.Clear();
            foreach (var destination in state.Destinations)
                Destinations.AddItem(destination.Name);
        }

        UpdateButton();
    }

    private void UpdateButton()
    {
        FTLButton.Disabled = !_hasShuttle ||
                             _selected == null ||
                             _state != FTLState.Available ||
                             !HasAccess();
    }

    private bool HasAccess()
    {
        return _player.LocalSession?.AttachedEntity is { } player &&
               _access.IsAllowed(player, _owner);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        UpdateButton();
        var progress = _ftlTime.ProgressAt(_timing.CurTime);
        FTLBar.Value = float.IsFinite(progress) ? progress : 1f;
    }
}
