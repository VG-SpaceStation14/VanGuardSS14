    private ResearchConsoleBoundInterfaceState _lastState = new(0);

    /// <summary>Disciplines currently shown as tabs, kept for rebuilds.</summary>
    private List<TechDisciplinePrototype> _disciplineProtos = new();

    private ButtonGroup _disciplineGroup = new();

    // Tree canvas pan state.
    private bool _panning;
    private Vector2 _panOffset;

