    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_quickFillRemaining > 0f)
            _quickFillRemaining = MathF.Max(0f, _quickFillRemaining - args.DeltaSeconds);

        // Revert optimistic unlocks the server has not confirmed in time.
        foreach (var id in _pendingUnlocks.Keys.ToList())
        {
            if (_gameTiming.CurTime - _pendingUnlocks[id] <= TimeSpan.FromSeconds(1.5))
                continue;

            _pendingUnlocks.Remove(id);
            _treeDirty = true;
        }

        // Track the hold-research fill time so it can resume after a rebuild.
        if (_holdFillTechId != null)
            _holdFillRemaining = MathF.Max(0f, _holdFillRemaining - args.DeltaSeconds);

        // Track the branch-research button hold time so it can survive panel rebuilds.
        if (_holdButtonTechId != null)
            _holdButtonRemaining = MathF.Max(0f, _holdButtonRemaining - args.DeltaSeconds);

        // Research the chain-research wave, one technology at a time.
        if (_waveQueue.Count > 0)
        {
            _waveDelay -= args.DeltaSeconds;
            if (_waveDelay <= 0f)
            {
                _waveDelay = WaveStaggerTime;
                var techId = _waveQueue.Dequeue();
                RequestUnlock(techId);
                StartQuickFill(techId);
            }
        }

        // Rebuild the tree after an optimistic unlock. This must not happen
        // while a node's own FrameUpdate is being processed (DoFrameUpdateRecursive
        // iterates the live children collection), so it is deferred to here.
        if (_treeDirty)
        {
            _treeDirty = false;
            if (_entity.TryGetComponent<TechnologyDatabaseComponent>(Entity, out var database))
            {
                RebuildTree();
                RefreshInfoPanel(database);
            }
        }
    }

    public void SetEntity(EntityUid entity)
