using System;
using System.Collections.Generic;
using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.VendingMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._VanGuard.VendingMachines.UI;

/// <summary>
///     Compact 640x600 vending machine window: bank balance on top, a search bar,
///     optional category tabs, and a four-column grid of
///     <see cref="FancyVendingMachineItemCard"/> item blocks.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FancyVendingMachineMenu : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private readonly SpriteSystem _spriteSystem;

    private readonly Dictionary<(InventoryType Type, string ID), FancyVendingMachineItemCard> _cards = new();
    private readonly Dictionary<(InventoryType Type, string ID), string> _names = new();
    private readonly List<VendingMachineInventoryEntry> _entries = new();
    private readonly List<VendingMachineInventoryCategory> _categories = new();

    private VendingMachineInventoryCategory? _selectedCategory;
    private bool _enabled;
    private bool _allForFree;
    private string _filter = string.Empty;

    /// <summary>
    ///     Invoked when the user clicks one of the item cards.
    /// </summary>
    public event Action<VendingMachineInventoryEntry>? OnItemSelected;

    public FancyVendingMachineMenu()
    {
        MinSize = SetSize = new Vector2(640, 600);
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _spriteSystem = _entityManager.System<SpriteSystem>();

        SearchBar.OnTextChanged += args => SetFilter(args.Text.Trim());
        EmptyLabel.Visible = false;
    }

    public void Populate(List<VendingMachineInventoryEntry> inventory, IReadOnlyList<VendingMachineInventoryCategory> categories, bool enabled, bool allForFree)
    {
        _enabled = enabled;
        _allForFree = allForFree;
        _entries.Clear();
        _names.Clear();
        _categories.Clear();
        _categories.AddRange(categories);

        foreach (var (_, card) in _cards)
        {
            ItemGrid.RemoveChild(card);
            card.Dispose();
        }
        _cards.Clear();

        foreach (var entry in inventory)
        {
            _entries.Add(entry);
        }

        PopulateCategories();
        RebuildGrid();
    }

    public void UpdateAmounts(List<VendingMachineInventoryEntry> inventory, bool enabled)
    {
        _enabled = enabled;
        _entries.Clear();

        var seen = new HashSet<(InventoryType, string)>();
        foreach (var entry in inventory)
        {
            _entries.Add(entry);
            var key = (entry.Type, entry.ID);
            seen.Add(key);

            if (_cards.TryGetValue(key, out var card))
            {
                card.SetAmount(entry.Amount);
                card.SetDisabled(!enabled || entry.Amount == 0);
                continue;
            }
        }

        foreach (var key in _cards.Keys.Where(k => !seen.Contains(k)).ToList())
        {
            RemoveCard(key);
        }

        // New entries (e.g. restock) need cards and may change which categories show up.
        PopulateCategories();
        RebuildGrid();
    }

    /// <summary>
    ///     Updates the balance header. A negative balance means the buyer has no
    ///     bank account.
    /// </summary>
    public void UpdateBalance(int balance)
    {
        BalanceLabel.Text = balance < 0
            ? Loc.GetString("vending-machine-ui-no-account")
            : Loc.GetString("vending-machine-ui-balance", ("balance", balance));
    }

    private void SetFilter(string filter)
    {
        _filter = filter;
        ApplyFilter();
    }

    private void PopulateCategories()
    {
        var visibleCategories = new List<VendingMachineInventoryCategory>();

        foreach (var category in _categories)
        {
            if (_entries.Any(entry => CategoryContains(category, entry)))
                visibleCategories.Add(category);
        }

        var showCategories = visibleCategories.Count > 1;
        CategoryPanel.Visible = showCategories;

        if (!showCategories)
        {
            _selectedCategory = null;
            CategoryTabs.SetTabs([], 0);
            return;
        }

        if (_selectedCategory != null && !visibleCategories.Contains(_selectedCategory))
            _selectedCategory = null;

        var allCategory = new TabBarEntry(
            Loc.GetString("vending-machine-category-all"),
            () => SelectCategory(null),
            new TabBarIcon(Size: new Vector2(32), StyleClass: "VendingAllCategoryIcon"));
        var choices = new List<TabBarEntry> { allCategory };
        var selectedIndex = 0;

        foreach (var category in visibleCategories)
        {
            var choice = new TabBarEntry(
                Loc.GetString(category.Name),
                () => SelectCategory(category),
                new TabBarIcon(_spriteSystem.Frame0(category.Icon), new Vector2(48)));
            choices.Add(choice);

            if (_selectedCategory == category)
                selectedIndex = choices.Count - 1;
        }

        CategoryTabs.SetTabs(choices, selectedIndex);
    }

    private void SelectCategory(VendingMachineInventoryCategory? category)
    {
        _selectedCategory = category;
        RebuildGrid();
    }

    private static bool CategoryContains(VendingMachineInventoryCategory category, VendingMachineInventoryEntry entry)
    {
        return category.GetInventory(entry.Type).ContainsKey(entry.ID);
    }

    private void RebuildGrid()
    {
        // Upstream parity: the search placeholder names the selected category.
        var categoryName = _selectedCategory?.Name ?? "vending-machine-category-all";
        SearchBar.PlaceHolder = CategoryPanel.Visible
            ? Loc.GetString("vending-machine-component-search-category-filter", ("category", Loc.GetString(categoryName)))
            : Loc.GetString("vending-machine-component-search-filter");

        foreach (var (_, card) in _cards)
        {
            ItemGrid.RemoveChild(card);
            card.Dispose();
        }
        _cards.Clear();

        foreach (var entry in _entries)
        {
            if (_selectedCategory is { } selected && !CategoryContains(selected, entry))
                continue;

            var card = CreateCard(entry);
            _cards[(entry.Type, entry.ID)] = card;
            ItemGrid.AddChild(card);
        }

        ApplyFilter();
    }

    private void ApplyFilter()
    {
        var hasMatches = false;
        foreach (var (key, card) in _cards)
        {
            _names.TryGetValue(key, out var name);
            var matches = string.IsNullOrEmpty(_filter)
                || key.ID.Contains(_filter, StringComparison.CurrentCultureIgnoreCase)
                || (name != null && name.Contains(_filter, StringComparison.CurrentCultureIgnoreCase));
            card.Visible = matches;
            hasMatches |= matches;
        }

        EmptyLabel.Text = _entries.Count == 0
            ? Loc.GetString("vending-machine-ui-out-of-stock")
            : Loc.GetString("vending-machine-ui-no-matches");
        EmptyLabel.Visible = !hasMatches;
        ItemGrid.Visible = hasMatches;
    }

    private void RemoveCard((InventoryType Type, string ID) key)
    {
        if (!_cards.Remove(key, out var card))
            return;

        _names.Remove(key);
        ItemGrid.RemoveChild(card);
        card.Dispose();
    }

    private FancyVendingMachineItemCard CreateCard(VendingMachineInventoryEntry entry)
    {
        var card = new FancyVendingMachineItemCard();
        var name = ResolveName(entry);
        _names[(entry.Type, entry.ID)] = name;
        card.SetItem(entry.ID, name, entry.Price, entry.Amount, _allForFree, _enabled);
        card.OnPressed += () => OnItemSelected?.Invoke(entry);
        return card;
    }

    private string ResolveName(VendingMachineInventoryEntry entry)
    {
        // EntityPrototype.Name is already localized (vanilla uses it directly for
        // display), so do not run it through Loc.GetString.
        if (_prototypeManager.TryIndex(entry.ID, out EntityPrototype? proto))
            return proto.Name;
        return entry.ID;
    }
}